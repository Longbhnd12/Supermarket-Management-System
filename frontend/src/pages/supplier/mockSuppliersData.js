export function getInitialLetter(name = '') {
    const trimmed = name.trim();
    if (!trimmed) return 'S';
    // If company starts with "Công ty Cổ phần Sữa Việt Nam (Vinamilk)", check parentheses first
    const match = trimmed.match(/\(([^)]+)\)/);
    if (match && match[1]) {
        return match[1].charAt(0).toUpperCase();
    }
    return trimmed.charAt(0).toUpperCase();
}

